"use client";

import React, { useState } from "react";
import { ChatMessage, SystemPromptConfig } from "@/lib/types";
import { compileSystemPrompt } from "@/lib/defaultPrompt";

interface PromptPayloadModalProps {
  isOpen: boolean;
  onClose: () => void;
  messages: ChatMessage[];
  systemPromptConfig: SystemPromptConfig;
  customSystemPrompt?: string;
  provider: "gemini" | "simulator";
}

export function PromptPayloadModal({
  isOpen,
  onClose,
  messages,
  systemPromptConfig,
  customSystemPrompt,
  provider,
}: PromptPayloadModalProps) {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const activeSystemPrompt =
    customSystemPrompt && customSystemPrompt.trim().length > 0
      ? customSystemPrompt
      : compileSystemPrompt(systemPromptConfig);

  const lastUserMsg = [...messages].reverse().find((m) => m.role === "user");

  const wirePayload = {
    provider,
    systemInstruction: activeSystemPrompt,
    conversationHistory: messages.map((m) => ({
      role: m.role,
      content: m.content,
      guardrailTriggered: m.guardrailTriggered || null,
    })),
    latestUserPrompt: lastUserMsg ? lastUserMsg.content : null,
  };

  const jsonString = JSON.stringify(wirePayload, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(jsonString);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="modal-overlay" onClick={onClose} role="dialog" aria-modal="true">
      <div className="modal-dialog" onClick={(e) => e.stopPropagation()}>
        <div className="modal-header">
          <div>
            <h3>🔍 Behind The Scenes: AI Prompt Inspector</h3>
            <p style={{ fontSize: "0.75rem", color: "var(--text-secondary)", marginTop: "2px" }}>
              Examine the separation between User Prompt and System Prompt in the API payload
            </p>
          </div>
          <button className="btn-icon" onClick={onClose}>
            ✕
          </button>
        </div>

        <div className="modal-body">
          <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: "12px" }}>
            <div
              style={{
                background: "rgba(76, 201, 240, 0.1)",
                border: "1px solid rgba(76, 201, 240, 0.3)",
                borderRadius: "8px",
                padding: "12px",
              }}
            >
              <div style={{ fontSize: "0.72rem", fontWeight: "700", color: "#7ce2ff", marginBottom: "4px" }}>
                USER PROMPT
              </div>
              <div style={{ fontSize: "0.82rem", color: "#f8fafc" }}>
                {lastUserMsg ? `"${lastUserMsg.content}"` : "(No user input yet)"}
              </div>
            </div>

            <div
              style={{
                background: "rgba(230, 57, 70, 0.1)",
                border: "1px solid rgba(230, 57, 70, 0.3)",
                borderRadius: "8px",
                padding: "12px",
              }}
            >
              <div style={{ fontSize: "0.72rem", fontWeight: "700", color: "#ff8591", marginBottom: "4px" }}>
                SYSTEM PROMPT (ROLE + STORE + GUARDRAILS)
              </div>
              <div style={{ fontSize: "0.82rem", color: "#f8fafc" }}>
                Active Length: {activeSystemPrompt.length} chars (~{Math.round(activeSystemPrompt.length / 4)} tokens)
              </div>
            </div>
          </div>

          <div>
            <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "8px" }}>
              <span style={{ fontSize: "0.78rem", fontWeight: "700", color: "var(--text-secondary)" }}>
                COMPLETE WIRE PAYLOAD (JSON)
              </span>
              <button className="btn-icon" style={{ fontSize: "0.7rem" }} onClick={handleCopy}>
                {copied ? "✓ Copied" : "📋 Copy JSON"}
              </button>
            </div>
            <pre className="raw-code-box" style={{ maxHeight: "320px" }}>
              {jsonString}
            </pre>
          </div>

          <div
            style={{
              background: "rgba(255, 255, 255, 0.04)",
              borderRadius: "8px",
              padding: "12px",
              fontSize: "0.78rem",
              color: "var(--text-secondary)",
              lineHeight: "1.5",
            }}
          >
            📌 <strong>Key Takeaway:</strong> The customer never sees the System Prompt, but every single token generated by the AI model is constrained and steered by it. This is how guardrails prevent unintended promises or free item giveaways.
          </div>
        </div>

        <div className="modal-footer">
          <button className="btn-secondary" onClick={onClose}>
            Close Inspector
          </button>
        </div>
      </div>
    </div>
  );
}
